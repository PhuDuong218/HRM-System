    private String accountBody(long employeeId, String username) {
        return "{\"employeeId\":" + employeeId + ",\"roleId\":3,\"username\":\"" + username
                + "\",\"password\":\"NewPassword@123\",\"confirmPassword\":\"NewPassword@123\",\"active\":true}";
    }
    private String token(long account, int version) { return jwt.issue(account, account, "unused", "ADMIN", version); }
    private JsonNode tree(HttpResponse<String> response) { return json.readTree(response.body()); }
    private HttpResponse<String> call(String method, String path, String token, String body) throws Exception {
        var request = HttpRequest.newBuilder(URI.create("http://localhost:" + port + "/api/admin" + path));
        if (token != null) request.header("Authorization", "Bearer " + token);
        if (body != null) request.header("Content-Type", "application/json");
        return client.send(request.method(method, body == null ? HttpRequest.BodyPublishers.noBody()
                : HttpRequest.BodyPublishers.ofString(body)).build(), HttpResponse.BodyHandlers.ofString());
    }
