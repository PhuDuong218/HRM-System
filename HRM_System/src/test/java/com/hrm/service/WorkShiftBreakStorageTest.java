package com.hrm.service;

import com.hrm.dto.DetailedWorkTimeDTOs.*;
import com.hrm.dto.WorkTimeDTOs.*;
import com.hrm.security.AuthenticatedAccount;
import java.sql.Timestamp;
import java.time.LocalTime;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.support.JdbcTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

public class WorkShiftBreakStorageTest {
    private JdbcTemplate db;
    private DetailedWorkTimeService service;
    private TransactionTemplate transaction;
    private final WorkShiftService shifts = mock(WorkShiftService.class);
    private final AuthenticatedAccount actor = new AuthenticatedAccount(1L, 1L, "admin", "ADMIN");
    private final ShiftInput input = new ShiftInput("DAY", "Ca ngày", LocalTime.of(8, 0), LocalTime.of(17, 0), 0, 60, true);
    private final ShiftView view = new ShiftView(9, "DAY", "Ca ngày", LocalTime.of(8, 0), LocalTime.of(17, 0), 0, 60, true);
    public static Timestamp utcNow() { return Timestamp.from(java.time.Instant.now()); }

    @BeforeEach void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MSSQLServer;DB_CLOSE_DELAY=-1", "sa", "");
        db = new JdbcTemplate(source);
        db.execute("CREATE SCHEMA dbo");
        db.execute("CREATE TABLE dbo.work_shifts(shift_id bigint PRIMARY KEY)");
        db.execute("CREATE TABLE dbo.work_shift_breaks(break_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shift_id bigint REFERENCES dbo.work_shifts(shift_id), break_start_offset_minutes int, break_end_offset_minutes int, superseded_at timestamp)");
        db.execute("CREATE ALIAS SYSUTCDATETIME FOR 'com.hrm.service.WorkShiftBreakStorageTest.utcNow'");
        transaction = new TransactionTemplate(new JdbcTransactionManager(source));
        service = new DetailedWorkTimeService(db, shifts, mock(WorkScheduleService.class));
        when(shifts.createWithVerifiedBreaks(eq(actor), any())).thenAnswer(call -> {
            db.update("INSERT INTO dbo.work_shifts VALUES(9)"); return view;
        });
        when(shifts.updateWithVerifiedBreaks(eq(actor), eq(9L), any())).thenReturn(view);
    }

    @Test void persistsNonzeroBreakAndKeepsSupersededHistory() {
        var original = new ShiftWithBreaks(input, List.of(new OffsetBreak(240, 300)));
        transaction.execute(status -> service.createShift(actor, original));
        assertEquals(original.breaks(), service.shiftBreaks(9));
        var updated = new ShiftWithBreaks(input, List.of(new OffsetBreak(120, 150), new OffsetBreak(240, 270)));
        transaction.execute(status -> service.updateShift(actor, 9, updated));
        assertEquals(updated.breaks(), service.shiftBreaks(9));
        assertEquals(1, db.queryForObject("SELECT COUNT(*) FROM dbo.work_shift_breaks WHERE superseded_at IS NOT NULL", Integer.class));
    }

    @Test void failedBreakInsertRollsBackParentAndAllBreaks() {
        db.execute("ALTER TABLE dbo.work_shift_breaks ADD CHECK(break_end_offset_minutes <= 300)");
        var request = new ShiftWithBreaks(input, List.of(new OffsetBreak(240, 270), new OffsetBreak(300, 330)));
        assertThrows(DataAccessException.class, () -> transaction.execute(status -> service.createShift(actor, request)));
        assertEquals(0, db.queryForObject("SELECT COUNT(*) FROM dbo.work_shifts", Integer.class));
        assertEquals(0, db.queryForObject("SELECT COUNT(*) FROM dbo.work_shift_breaks", Integer.class));
    }
}
